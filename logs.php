        $where[] = "DATE(created_at) >= ?";
        $params[] = $startDate;
    }

    if (!empty($endDate)) {
        $where[] = "DATE(created_at) <= ?";
        $params[] = $endDate;
    }

    if (!empty($searchQuery)) {
        $where[] = "(description LIKE ? OR username LIKE ? OR ip_address LIKE ?)";
        $searchTerm = "%$searchQuery%";
        $params[] = $searchTerm;
        $params[] = $searchTerm;
        $params[] = $searchTerm;
    }

    $exportSql = "SELECT * FROM activity_logs WHERE " . implode(' AND ', $where) . " ORDER BY id DESC";
    $exportStmt = $pdo->prepare($exportSql);
    $exportStmt->execute($params);

