// Badge & Icon Formatting Helper
function getActionBadgeHTML($action) {
    switch ($action) {
        case 'login':
            return '<span class="badge" style="background: #E8F5E9; color: #2E7D32; font-weight: 600;">🔑 Login</span>';
        case 'logout':
            return '<span class="badge" style="background: #ECEFF1; color: #455A64; font-weight: 600;">🚪 Logout</span>';
        case 'login_failed':
            return '<span class="badge" style="background: #FFEBEE; color: #C62828; font-weight: 600;">⚠️ Failed Login</span>';
        case 'pig_created':
            return '<span class="badge" style="background: #E8F5E9; color: #1B5E20; font-weight: 600;">🐷 Pig Registered</span>';
        case 'pig_updated':
            return '<span class="badge" style="background: #FFF8E1; color: #F57F17; font-weight: 600;">✏️ Pig Updated</span>';
        case 'pig_status_changed':
            return '<span class="badge" style="background: #FFF3E0; color: #E65100; font-weight: 600;">🔄 Status Change</span>';
        case 'growth_added':
            return '<span class="badge" style="background: #E1F5FE; color: #0288D1; font-weight: 600;">⚖️ Weight Logged</span>';
        case 'vaccination_added':
            return '<span class="badge" style="background: #E0F2F1; color: #00695C; font-weight: 600;">💉 Health Logged</span>';
        case 'breeding_added':
            return '<span class="badge" style="background: #FCE4EC; color: #C2185B; font-weight: 600;">🍼 Breeding Logged</span>';
        case 'user_created':
            return '<span class="badge" style="background: #EDE7F6; color: #512DA8; font-weight: 600;">👤 User Created</span>';
        case 'user_updated':
            return '<span class="badge" style="background: #EDE7F6; color: #512DA8; font-weight: 600;">⚙️ User Updated</span>';
        case 'profile_updated':
            return '<span class="badge" style="background: #E8EAF6; color: #303F9F; font-weight: 600;">👤 Profile Updated</span>';
        case 'password_changed':
            return '<span class="badge" style="background: #E8EAF6; color: #303F9F; font-weight: 600;">🔒 Password Changed</span>';
        case 'report_exported':
            return '<span class="badge" style="background: #E0F7FA; color: #0097A7; font-weight: 600;">📥 Report Exported</span>';
        default:
            return '<span class="badge" style="background: #F5F5F5; color: #616161; font-weight: 600;">' . htmlspecialchars($action) . '</span>';
    }
}

